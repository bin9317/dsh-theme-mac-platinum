import { readFile, writeFile } from 'node:fs/promises';

const css = await readFile(new URL('./theme.css', import.meta.url), 'utf8');
const names = {
  paper: 'alias-bg-base alias-bg-document-preview',
  composer: 'specific-input-major',
  panel: 'alias-bg-layer-2 alias-bg-module-platform specific-sidebar-fill specific-sidebar-glass-fill',
  raised: 'alias-bg-layer-1 alias-bg-layer-3 alias-bg-overlay alias-card-fill alias-card-tile-fill alias-button-elevated-fill specific-menu specific-selector alias-markdown-code-block',
  rule: 'alias-border-l3 alias-scrollbar-bg-l1',
  edge: 'alias-border-l4 alias-scrollbar-hover-l1',
  ink: 'alias-label-primary alias-label-primary-bluish',
  muted: 'alias-label-secondary alias-label-tertiary',
  accent: 'alias-brand-primary alias-brand-text alias-link alias-border-selected',
  button: 'alias-button-primary-fill alias-button-info-fill',
  'accent-hover': 'alias-button-primary-hover alias-button-info-hover',
  selection: 'alias-bg-document-selection alias-bg-multi-select alias-interactive-bg-active specific-bubble specific-bubble-highlight',
  hover: 'alias-interactive-bg-hover alias-interactive-bg-hover-solid alias-interactive-bg-hover-accent alias-card-fill-hover alias-button-tool-bar-hover',
  'on-accent': 'alias-label-on-color alias-label-primary-foreground',
};
const tokens = Object.fromEntries(Object.entries(names).flatMap(([color, keys]) =>
  keys.split(' ').map(key => [`--dsw-${key}`, { light: `var(--platinum-${color})`, dark: `var(--platinum-${color})` }])
));
const factory = `const css = ${JSON.stringify(css)};
const tokens = ${JSON.stringify(tokens, null, 2)};

function alignSidebarHeader(root) {
  const selector = 'header[data-window-drag]:has([data-conversation-header-leading])';
  const heightProperty = '--platinum-conversation-header-height';
  let header = null;

  const resize = new ResizeObserver(() => {
    if (header) root.style.setProperty(heightProperty, header.getBoundingClientRect().height + 'px');
  });

  function connect() {
    if (header?.isConnected) return;
    const next = document.querySelector(selector);
    if (next === header) return;
    resize.disconnect();
    header = next;
    if (header) {
      resize.observe(header, { box: 'border-box' });
    } else {
      root.style.removeProperty(heightProperty);
    }
  }

  const changes = new MutationObserver(connect);
  changes.observe(document.body, { childList: true, subtree: true });
  connect();

  return () => {
    changes.disconnect();
    resize.disconnect();
    root.style.removeProperty(heightProperty);
  };
}

function apply(ctx) {
  ctx.effect(() => {
    const root = document.documentElement;
    const style = document.createElement('style');
    style.textContent = css;
    const releaseTokens = ctx.theme.overrideTokens('dsh-platinum-theme', tokens);
    document.head.append(style);
    root.setAttribute('data-dsh-platinum', '');
    const releaseHeaderAlignment = alignSidebarHeader(root);
    return () => {
      releaseHeaderAlignment();
      root.removeAttribute('data-dsh-platinum');
      style.remove();
      releaseTokens();
    };
  }, 'Platinum appearance');
}

return { inject: ['theme'], apply };`;
const body = factory.split('\n').map(line => line ? '    ' + line : '').join('\n');
await writeFile(new URL('./client.js', import.meta.url), `// Generated by build.mjs
window.__ModuleLoader__.load({
  id: 'dsh-platinum-theme',
  factory() {
${body}
  }
});
`);
